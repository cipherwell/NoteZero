package com.cipherwell.notezero.model

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.util.TimeZone

/**
 * Wire-format tests for the generated blank PDF: it must be a real PDF (correct xref offsets
 * and trailer), deterministic, and tiny. Device rendering (PdfRenderer accepting it) is covered
 * by the instrumented test; this one is pure JVM.
 */
class BlankPdfTest {

    private val text: String = String(BlankPdf.create(), Charsets.US_ASCII)

    @Test
    fun `generated bytes are a valid one page pdf`() {
        assertTrue(text.startsWith("%PDF-1.4\n"))
        assertTrue(text.endsWith("%%EOF\n"))
        assertTrue(text.contains("/Type /Catalog"))
        assertTrue(text.contains("/Type /Pages /Kids [3 0 R] /Count 1"))
        assertTrue(text.contains("/MediaBox [0 0 595 842]"))
        assertTrue(text.contains("/Length 0"))
    }

    @Test
    fun `xref offsets point at their objects and startxref points at the table`() {
        val startxref = Regex("startxref\n(\\d+)\n%%EOF").find(text)
            ?: error("missing trailer")
        val xrefOffset = startxref.groupValues[1].toInt()
        assertTrue(text.startsWith("xref", xrefOffset))

        val lines = text.substring(xrefOffset).lineSequence().toList()
        assertEquals("xref", lines[0])
        assertEquals("0 5", lines[1])
        assertEquals("0000000000 65535 f ", lines[2])
        // Objects 1..4 follow in order; each offset must land on "<n> 0 obj".
        for (objectNumber in 1..4) {
            val line = lines[2 + objectNumber]
            val offset = line.substring(0, 10).toInt()
            assertTrue(
                "object $objectNumber offset $offset",
                text.startsWith("$objectNumber 0 obj", offset),
            )
        }
    }

    @Test
    fun `output is deterministic and small`() {
        assertArrayEquals(BlankPdf.create(), BlankPdf.create())
        assertTrue(BlankPdf.create().size in 200..1024)
        assertEquals("application/pdf", BlankPdf.MIME_TYPE)
    }

    @Test
    fun `file names are deterministic ascii display data`() {
        val utc = TimeZone.getTimeZone("UTC")
        val name = BlankPdf.fileName(1_700_000_000_000L, utc)
        assertEquals("document-20231114-221320.pdf", name)
        assertEquals(name, BlankPdf.fileName(1_700_000_000_000L, utc))
        assertTrue(name.none { it.code > 127 })
    }
}
