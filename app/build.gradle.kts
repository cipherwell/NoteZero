    // Screenshot protection (FLAG_SECURE) is always on in production. Automated UI
    // verification may opt in explicitly:
    //   ./gradlew assembleDebug -PallowScreenshots=true
    buildConfigField(
      "boolean",
      "ALLOW_SCREENSHOTS",
      (project.findProperty("allowScreenshots") as String? ?: "false"),
    )
    // Dev-only convenience for instrumented tests; release builds never pass the flag.
    buildConfigField(
      "boolean",
      "DEV_DISABLE_AUTO_LOCK",
      (project.findProperty("devDisableAutoLock") as String? ?: "false"),
    )
  }

  // Production signing is supplied via env vars (CI secrets or a local key store outside
  // the repo). NoteZero has its OWN upload key; never reuse VaultZero's key.
  //   NOTEZERO_KEYSTORE_PATH, NOTEZERO_STORE_PASSWORD, NOTEZERO_KEY_PASSWORD
  //   NOTEZERO_KEY_ALIAS (default: notezero-upload)
  // When absent (F-Droid build server, third-party builders) the release variant stays
  // UNSIGNED so the distributor signs it with their own key. Never fall back to a debug key.
  val releaseKeystorePath = System.getenv("NOTEZERO_KEYSTORE_PATH")
  val releaseStorePassword = System.getenv("NOTEZERO_STORE_PASSWORD")
  val releaseKeyPassword = System.getenv("NOTEZERO_KEY_PASSWORD")
  val releaseKeyAlias = System.getenv("NOTEZERO_KEY_ALIAS") ?: "notezero-upload"
  val hasReleaseSigning = !releaseKeystorePath.isNullOrBlank() &&
    !releaseStorePassword.isNullOrBlank() &&
    !releaseKeyPassword.isNullOrBlank() &&
    file(releaseKeystorePath).exists()

  signingConfigs {
    create("release") {
      if (hasReleaseSigning) {
        storeFile = file(releaseKeystorePath!!)
        storePassword = releaseStorePassword
        keyAlias = releaseKeyAlias
        keyPassword = releaseKeyPassword
      }
    }
    // Local debug key generated by scripts/gen-debug-keystore.sh (gitignored).
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = true
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = if (hasReleaseSigning) signingConfigs.getByName("release") else null
    }
    debug {
      signingConfig = signingConfigs.getByName("debugConfig")
    }
  }

  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
  }
  buildFeatures {
    compose = true
